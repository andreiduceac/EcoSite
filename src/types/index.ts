import type { Feature, Polygon, Position } from 'geojson';
export type SitePolygon = Feature<Polygon>;
export type DataType = 'MEASURED' | 'CALCULATED' | 'ESTIMATED';
export type ServiceError = { kind: 'network' | 'rate_limit' | 'invalid_input' | 'no_data'; message: string };
export type Result<T> = { ok: true; data: T } | { ok: false; error: ServiceError };
export type Coordinate = { lat: number; lon: number };
export type SiteGeometry = { areaHa: number; areaM2: number; perimeterKm: number; centroid: Coordinate; antimeridian: boolean; vertices: number };
export const MONTHS = ['JAN','FEB','MAR','APR','MAY','JUN','JUL','AUG','SEP','OCT','NOV','DEC'] as const;
export type Month = typeof MONTHS[number];
export type ClimateParameter = 'ALLSKY_SFC_SW_DWN' | 'CLRSKY_SFC_SW_DWN' | 'T2M' | 'PRECTOTCORR' | 'WS10M' | 'WS50M' | 'WD50M';
export type MonthlyValues = Partial<Record<Month | 'ANN', number>>;
export type Climate = { parameters: Partial<Record<ClimateParameter, MonthlyValues>>; source: string; period: string; captured?: string };
export type WindObservation = { date: string; speed: number; direction: number };
export type DailyWind = { observations: WindObservation[]; period: string };
export type ElevationSample = { position: Position; elevation: number; row: number; col: number };
export type ElevationGrid = { samples: ElevationSample[]; spacingM: number; source: string };
export type OsmFeature = { id: string; category: 'road' | 'powerLine' | 'substation' | 'protected' | 'water' | 'forest' | 'building'; feature: Feature; name?: string };
export type OsmData = { features: OsmFeature[]; source: string; fetchedAt: string; incompleteAreas: number; radiusKm: number };
export type ComponentKey = 'solar' | 'wind' | 'environment' | 'terrain' | 'infrastructure';
export type ScoreComponent = { score: number | null; reason?: string; type: DataType };
export type ComponentScores = Record<ComponentKey, ScoreComponent>;
